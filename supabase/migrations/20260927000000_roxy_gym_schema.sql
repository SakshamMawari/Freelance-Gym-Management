-- 1. Profiles Table (linked to Supabase Auth)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  phone text,
  address text,
  role text not null default 'member' check (role in ('admin', 'member')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 2. Gym Plans Table
create table if not exists public.plans (
  id uuid primary key default gen_random_uuid(),
  plan_name text not null unique,
  duration_days integer not null check (duration_days > 0),
  price numeric(10,2) not null check (price >= 0),
  created_at timestamptz not null default now()
);

-- 3. Members Table
create table if not exists public.members (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  name text not null,
  phone text not null,
  email text,
  address text,
  photo_url text,
  plan_id uuid references public.plans(id) on delete set null,
  plan_name text,
  start_date date not null default current_date,
  expiry_date date not null,
  amount numeric(10,2) not null default 0 check (amount >= 0),
  payment_status text not null default 'pending' check (payment_status in ('paid', 'pending', 'cancelled')),
  payment_method text default 'UPI' check (payment_method in ('UPI', 'Cash', 'Card', 'Pending')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 4. Payments Ledger Table
create table if not exists public.payments (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.members(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  plan_name text,
  amount numeric(10,2) not null check (amount >= 0),
  method text not null default 'UPI' check (method in ('UPI', 'Cash', 'Card', 'Pending')),
  status text not null default 'paid' check (status in ('paid', 'pending')),
  payment_date date not null default current_date,
  created_at timestamptz not null default now()
);

-- 5. Attendance / Check-ins Table
create table if not exists public.attendance (
  id uuid primary key default gen_random_uuid(),
  member_id uuid not null references public.members(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  check_in_time timestamptz not null default now()
);

-- 6. Sample Todos Table (Ensures starter checks & quickstart tests succeed)
create table if not exists public.todos (
  id bigint generated by default as identity primary key,
